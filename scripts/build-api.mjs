// Bundles server/ask.ts into the self-contained Vercel function api/ask.js.
// Used by `npm run build:api` and by tests/ask/apiBuild.test.ts (stale check).
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const HEADER = '// GENERATED by npm run build:api - do not edit. Source: server/ask.ts\n';

export async function bundleAsk() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('../server/ask.ts', import.meta.url))],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    legalComments: 'none',
    logLevel: 'error',
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../api/ask.js', import.meta.url));
  writeFileSync(out, await bundleAsk());
  console.log('wrote api/ask.js');
}
